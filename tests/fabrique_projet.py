"""ملفات مسار وهمية لخطة عمل مشروع المؤسسة (نفس البنية، بعمليات مخترعة)."""

from pathlib import Path

from openpyxl import Workbook

ENTETE_RAPPORT = {2: "تاريخ النهاية", 3: "تاريخ البداية", 4: "أسطر الصرف", 5: "مجالات الصرف", 6: "قيمة المساهمة",
                  10: "الجهة المساهمة", 12: "ميزانية جمعية النجاح", 15: "المبلغ ", 16: "اولوية", 17: "العملية",
                  22: "رقم", 24: "التقييم", 28: "المعيار  الفرعي"}


def _ligne(ws, n, d):
    for j, v in d.items():
        ws.cell(n, j + 1, v)


def rapport_plan_action(chemin: Path, variante: int = 1) -> Path:
    """على شكل تقرير «خطة العمل»: سطر للمحور، سطر للمعيار، سطر العناوين، ثم العمليات."""
    wb = Workbook()
    ws = wb.active
    ws.title = "ReportPlanActionVersionComplet"
    _ligne(ws, 1, {1: " خطة العمل "})
    _ligne(ws, 4, {9: "التوصيف", 20: "القيمة", 27: "الأولوية"})
    _ligne(ws, 5, {8: "عمليات درجة أهميتها مرتفعة", 20: 1, 27: "الأولوية 1"})
    n = 7
    blocs = [("التلميذ", " 11 : الأنشطة الموازية  ", [
        ("30/06/2027", "01/09/2026", "مصاريف التنقل", "الأندية التربوية", 0, 2500, 2500, 1, "تنظيم خرجة تربوية وهمية",
         1, "نعم، منخرطة بشكل غير فعال", "المؤسسة منخرطة في برنامج"),
        ("31/10/2026", "01/10/2026", "معدات", "التجهيزات", 0, 3000, 3000, 2, "اقتناء قصص للمكتبة الوهمية", 2,
         "نعم", None)]),
        ("المؤسسة التعليمية", "2 : الأمن والنظافة", [
            ("10/09/2026", "01/09/2026", "معدات معلوماتية", "التجهيزات", 0, 1500 * variante, 1500 * variante, 1,
             "تعبئة طفايات الحريق الوهمية", 1, "نسبيا", "تتوفر المؤسسة على معدات")])]
    for axe, critere, ops in blocs:
        _ligne(ws, n, {2: axe, 28: "المحور"})
        _ligne(ws, n + 1, {2: critere, 28: "المعيار"})
        _ligne(ws, n + 2, ENTETE_RAPPORT)
        n += 3
        for o in ops:
            _ligne(ws, n, dict(zip([2, 3, 4, 5, 6, 12, 15, 16, 17, 22, 24, 28], o)))
            n += 1
    _ligne(ws, n + 2, {25: "في طور الإعداد."})
    wb.save(chemin)
    return chemin


