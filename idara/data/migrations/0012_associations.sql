-- التدبير المالي للجمعيات (اقتراح المدير 2026-11-02): نموذج المدير (قاعدة Access) لجمعية دعم مدرسة النجاح.
-- الأبواب والبنود وملاحظاتها منقولة كما هي من نموذج المدير (جدول AssBaseD).
CREATE TABLE association (
  id        INTEGER PRIMARY KEY,
  type      TEXT NOT NULL UNIQUE CHECK (type IN ('najah','sportive','cooperative')),
  nom       TEXT NOT NULL,
  rib       TEXT,
  president TEXT,
  tresorier TEXT,
  date_renouvellement TEXT
);
INSERT INTO association(type, nom) VALUES ('najah', 'جمعية دعم مدرسة النجاح');

CREATE TABLE rubrique (                      -- أبواب وبنود الميزانية
  id        INTEGER PRIMARY KEY,
  type_association TEXT NOT NULL,
  sens      TEXT NOT NULL CHECK (sens IN ('recette','depense')),
  chapitre  TEXT NOT NULL,
  ligne     TEXT NOT NULL,
  observation TEXT,
  ordre     INTEGER NOT NULL
);

CREATE TABLE exercice (                      -- السنة المالية للجمعية
  id             INTEGER PRIMARY KEY,
  association_id INTEGER NOT NULL REFERENCES association(id),
  libelle        TEXT NOT NULL,
  date_debut     TEXT NOT NULL,
  date_fin       TEXT NOT NULL,
  UNIQUE (association_id, libelle),
  CHECK (date_fin > date_debut)
);

CREATE TABLE prevision (                     -- الميزانية التوقعية
  exercice_id INTEGER NOT NULL REFERENCES exercice(id) ON DELETE CASCADE,
  rubrique_id INTEGER NOT NULL REFERENCES rubrique(id),
  montant     REAL NOT NULL DEFAULT 0 CHECK (montant >= 0),
  PRIMARY KEY (exercice_id, rubrique_id)
);

CREATE TABLE operation_financiere (
  id          INTEGER PRIMARY KEY,
  exercice_id INTEGER NOT NULL REFERENCES exercice(id) ON DELETE CASCADE,
  numero      INTEGER NOT NULL,
  date_op     TEXT NOT NULL,
  nature      TEXT NOT NULL CHECK (nature IN ('recette','depense','transfert')),
  registre    TEXT NOT NULL CHECK (registre IN ('banque','caisse')),  -- للتحويل: السجل المصدر
  rubrique_id INTEGER REFERENCES rubrique(id),
  montant     REAL NOT NULL CHECK (montant > 0),
  reference   TEXT,                          -- فاتورة، سند الطلب، كشف الحساب...
  detail      TEXT,
  observation TEXT,
  UNIQUE (exercice_id, numero),
  CHECK ((nature = 'transfert') = (rubrique_id IS NULL))
);

